    // =========================================================
    // ANDROID KEYSTORE
    // =========================================================

    private fun getOrCreateKey(): SecretKey {

        val keyStore =
            KeyStore.getInstance(
                KEYSTORE
            )

        keyStore.load(null)

        if (
            keyStore.containsAlias(
                KEY_ALIAS
            )
        ) {

            return keyStore.getKey(
                KEY_ALIAS,
                null
            ) as SecretKey
        }

        val keyGenerator =
            KeyGenerator.getInstance(
                KeyProperties.KEY_ALGORITHM_AES,
                KEYSTORE
            )

        val keySpec =
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or
                        KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(
                    KeyProperties.BLOCK_MODE_GCM
                )
                .setEncryptionPaddings(
                    KeyProperties.ENCRYPTION_PADDING_NONE
                )
                .setKeySize(256)
                .build()

        keyGenerator.init(
            keySpec
        )

        return keyGenerator.generateKey()
    }

    // =========================================================
    // ENCRYPT
    // =========================================================

    private fun encrypt(
        plainText: String
    ): String {

        val cipher =
            Cipher.getInstance(
                TRANSFORMATION
            )

        /*
         * IMPORTANT:
         *
         * Do not provide our own GCMParameterSpec
         * during encryption.
         *
         * Android Keystore generates the IV itself.
         */
        cipher.init(
            Cipher.ENCRYPT_MODE,
            getOrCreateKey()
        )

        /*
         * Get the IV generated by Android Keystore.
         */
        val iv =
            cipher.iv

        if (
            iv == null ||
            iv.size != IV_LENGTH
        ) {

            throw IllegalStateException(
                "Android Keystore returned an invalid AES-GCM IV."
            )
        }

        val encrypted =
            cipher.doFinal(
                plainText.toByteArray(
                    StandardCharsets.UTF_8
                )
            )

        /*
         * Stored format:
         *
         * IV + encrypted data
         */
        val combined =
            ByteArray(
                iv.size +
                        encrypted.size
            )

        System.arraycopy(
            iv,
            0,
            combined,
            0,
            iv.size
        )

        System.arraycopy(
            encrypted,
            0,
            combined,
            iv.size,
            encrypted.size
        )

        return Base64.encodeToString(
            combined,
            Base64.NO_WRAP
        )
    }

    // =========================================================
    // DECRYPT
    // =========================================================

    private fun decrypt(
        encryptedText: String
    ): String? {

        return try {

            val combined =
                Base64.decode(
                    encryptedText,
                    Base64.NO_WRAP
                )

            if (
                combined.size <= IV_LENGTH
            ) {

                return null
            }

            val iv =
                combined.copyOfRange(
                    0,
                    IV_LENGTH
                )

            val encrypted =
                combined.copyOfRange(
                    IV_LENGTH,
                    combined.size
                )

            val cipher =
                Cipher.getInstance(
                    TRANSFORMATION
                )

            val gcmSpec =
                GCMParameterSpec(
                    GCM_TAG_LENGTH,
                    iv
                )

            cipher.init(
                Cipher.DECRYPT_MODE,
                getOrCreateKey(),
                gcmSpec
            )

            val decrypted =
                cipher.doFinal(
                    encrypted
                )

            String(
                decrypted,
                StandardCharsets.UTF_8
            )

        } catch (
            e: Exception
        ) {

            null
        }
    }

    // =========================================================
    // GENERIC ENCRYPTED STORAGE
    // =========================================================

    fun save(
        key: String,
        value: String
    ) {

        val encrypted =
            encrypt(
                value
            )

        context()
            .getSharedPreferences(
                PREF_NAME,
                Context.MODE_PRIVATE
            )
            .edit()
            .putString(
                key,
                encrypted
            )
            .apply()
    }

    fun get(
        key: String
    ): String? {

        val encrypted =
            context()
                .getSharedPreferences(
                    PREF_NAME,
                    Context.MODE_PRIVATE
                )
                .getString(
                    key,
                    null
                )
                ?: return null

        return decrypt(
            encrypted
        )
    }

    fun remove(
        key: String
    ) {

        context()
            .getSharedPreferences(
                PREF_NAME,
                Context.MODE_PRIVATE
            )
            .edit()
            .remove(
                key
            )
            .apply()
    }

    fun contains(
        key: String
    ): Boolean {

        return context()
            .getSharedPreferences(
                PREF_NAME,
                Context.MODE_PRIVATE
            )
            .contains(
                key
            )
    }

    fun clearAll() {

        context()
            .getSharedPreferences(
                PREF_NAME,
                Context.MODE_PRIVATE
            )
            .edit()
            .clear()
            .apply()
    }

