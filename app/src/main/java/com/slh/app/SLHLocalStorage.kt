    private fun jsonToNotice(
        json: JSONObject
    ): CoachingNotice {

        val statusName =
            json.optString("status", "ACTIVE")

        val readIds = mutableListOf<String>()
        val readArray = json.optJSONArray("readByUserIds")
        if (readArray != null) {
            for (i in 0 until readArray.length()) {
                readIds.add(readArray.optString(i))
            }
        }

        return CoachingNotice(
            id = json.optString("id"),
            coachingId = json.optString("coachingId"),
            batchId = json.optString("batchId"),
            title = json.optString("title"),
            message = json.optString("message"),
            noticeDate = json.optString("noticeDate"),
            expiryDate = json.optString("expiryDate"),
            createdById = json.optString("createdById"),
            createdByName = json.optString("createdByName"),
            status =
                try {
                    NoticeStatus.valueOf(statusName)
                } catch (e: Exception) {
                    NoticeStatus.ACTIVE
                },
            readByUserIds = readIds
        )
    }

